alter table public.ordonnances enable row level security;
alter table public.ordonnance_lignes enable row level security;
alter table public.produits_pharmacie enable row level security;
alter table public.commandes_pharmacie enable row level security;
alter table public.ventes_comptoir enable row level security;
alter table public.resultats_analyses enable row level security;
