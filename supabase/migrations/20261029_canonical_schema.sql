-- Ordonnance Mobile canonical schema
-- Source of truth: approved SQL specification.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('patient','medecin','infirmier','pharmacien','admin','superadmin')),
  hopital_id bigint,
  pharmacie_id bigint,
  nom text,
  prenom text,
  telephone text,
  created_at timestamptz default now()
);

create table if not exists public.patients (
  id uuid primary key default gen_random_uuid(), user_id uuid references auth.users(id) on delete set null,
  nom text not null, prenom text not null, telephone text, date_naissance date, created_at timestamptz default now()
);

create table if not exists public.hopitaux (
  id bigint generated by default as identity primary key, nom text not null, adresse text, ville text,
  telephone text, prix_consultation numeric(10,2) default 0, publie boolean default false,
  statut text default 'en_attente', created_at timestamptz default now()
);

create table if not exists public.pharmacies (
  id bigint generated by default as identity primary key, nom text not null, adresse text, ville text,
  telephone text, publie boolean default false, statut text default 'en_attente', created_at timestamptz default now()
);

create table if not exists public.rendez_vous (
  id bigint generated by default as identity primary key, patient_id uuid references public.patients(id),
  hopital_id bigint references public.hopitaux(id), specialite text, symptomes text,
  statut text default 'attente' check (statut in ('attente','constantes','termine','annule')),
  montant numeric(10,2), mode_paiement text, medecin_id uuid references auth.users(id), created_at timestamptz default now()
);

create table if not exists public.constantes (
  id bigint generated by default as identity primary key, rendez_vous_id bigint references public.rendez_vous(id) on delete cascade,
  temperature numeric(4,1), tension text, poids numeric(5,1), saisi_par uuid references auth.users(id), created_at timestamptz default now()
);

create table if not exists public.ordonnances (
  id bigint generated by default as identity primary key, rendez_vous_id bigint references public.rendez_vous(id),
  patient_id uuid references public.patients(id), hopital_id bigint references public.hopitaux(id),
  medecin_id uuid references auth.users(id), signature text, created_at timestamptz default now()
);

create table if not exists public.ordonnance_lignes (
  id bigint generated by default as identity primary key, ordonnance_id bigint references public.ordonnances(id) on delete cascade,
  medicament text not null, posologie text, quantite integer default 1
);

create table if not exists public.produits_pharmacie (
  id bigint generated by default as identity primary key, pharmacie_id bigint references public.pharmacies(id),
  nom text not null, prix numeric(10,2), quantite integer default 0, created_at timestamptz default now()
);

create table if not exists public.commandes_pharmacie (
  id bigint generated by default as identity primary key, patient_id uuid references public.patients(id),
  pharmacie_id bigint references public.pharmacies(id), ordonnance_id bigint references public.ordonnances(id),
  ligne_id bigint references public.ordonnance_lignes(id), produit text, montant numeric(10,2), mode_paiement text,
  statut text default 'en_attente' check (statut in ('en_attente','delivree','annulee')), created_at timestamptz default now()
);

create table if not exists public.ventes_comptoir (
  id bigint generated by default as identity primary key, pharmacie_id bigint references public.pharmacies(id),
  produit_id bigint references public.produits_pharmacie(id), produit text, quantite integer default 1,
  montant numeric(10,2), mode_paiement text, created_at timestamptz default now()
);

create table if not exists public.resultats_analyses (
  id bigint generated by default as identity primary key, patient_id uuid references public.patients(id),
  rendez_vous_id bigint references public.rendez_vous(id), type_analyse text, resultat text, fichier_url text, created_at timestamptz default now()
);

create table if not exists public.avis (
  id bigint generated by default as identity primary key, patient_id uuid references public.patients(id),
  hopital_id bigint references public.hopitaux(id), pharmacie_id bigint references public.pharmacies(id),
  note integer check (note between 1 and 5), commentaire text, created_at timestamptz default now()
);

create index if not exists idx_rdv_patient on public.rendez_vous(patient_id);
create index if not exists idx_rdv_hopital on public.rendez_vous(hopital_id);
create index if not exists idx_ord_patient on public.ordonnances(patient_id);
create index if not exists idx_cmd_patient on public.commandes_pharmacie(patient_id);
create index if not exists idx_cmd_pharmacie on public.commandes_pharmacie(pharmacie_id);

