-- Extension feuilles d'assurance Ordonnance Mobile.
-- À appliquer dans le SQL Editor Supabase avant d'activer le module.
create table if not exists public.modeles_assurance (
 id bigint generated by default as identity primary key,
 assurance text not null,
 nom text not null,
 description text,
 structure_json jsonb not null default '{}'::jsonb,
 photo_path text,
 statut text not null default 'en_attente' check (statut in ('en_attente','approuve','refuse')),
 cree_par uuid not null references auth.users(id),
 hopital_id bigint references public.hopitaux(id),
 approuve_par uuid references auth.users(id),
 approuve_le timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.feuilles_assurance (
 id bigint generated by default as identity primary key,
 patient_id uuid not null references public.patients(id),
 hopital_id bigint references public.hopitaux(id),
 medecin_id uuid references auth.users(id),
 modele_id bigint references public.modeles_assurance(id),
 assurance text not null,
 numero_assure text,
 assure_nom text,
 assure_prenom text,
 assure_naissance date,
 assure_telephone text,
 donnees_medicales jsonb not null default '{}'::jsonb,
 statut text not null default 'brouillon' check (statut in ('brouillon','validee','annulee')),
 validee_par uuid references auth.users(id),
 validee_le timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.delivrances_pharmacie (
 id bigint generated by default as identity primary key,
 feuille_id bigint not null references public.feuilles_assurance(id) on delete cascade,
 pharmacie_id bigint references public.pharmacies(id),
 pharmacien_id uuid references auth.users(id),
 code_delivrance text not null,
 medicaments_delivres text not null,
 remarques text,
 created_at timestamptz not null default now()
);
create table if not exists public.journal_feuilles_assurance (
 id bigint generated by default as identity primary key,
 acteur_id uuid references auth.users(id),
 action text not null,
 table_cible text not null,
 id_cible text,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index if not exists modeles_assurance_statut_idx on public.modeles_assurance(statut);
create index if not exists feuilles_assurance_patient_idx on public.feuilles_assurance(patient_id,created_at desc);
create index if not exists feuilles_assurance_statut_idx on public.feuilles_assurance(statut);
create index if not exists delivrances_feuille_idx on public.delivrances_pharmacie(feuille_id);

alter table public.modeles_assurance enable row level security;
alter table public.feuilles_assurance enable row level security;
alter table public.delivrances_pharmacie enable row level security;
alter table public.journal_feuilles_assurance enable row level security;

-- Policies intentionally depend on the existing profiles role/ownership model.
drop policy if exists assurance_templates_select on public.modeles_assurance;
create policy assurance_templates_select on public.modeles_assurance for select to authenticated using (
 statut='approuve' or cree_par=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
);
drop policy if exists assurance_templates_insert on public.modeles_assurance;
create policy assurance_templates_insert on public.modeles_assurance for insert to authenticated with check (
 cree_par=auth.uid() and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin','medecin','infirmier'))
);
drop policy if exists assurance_templates_update on public.modeles_assurance;
create policy assurance_templates_update on public.modeles_assurance for update to authenticated using (
 cree_par=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
) with check (true);

drop policy if exists assurance_sheets_select on public.feuilles_assurance;
create policy assurance_sheets_select on public.feuilles_assurance for select to authenticated using (
 medecin_id=auth.uid() or patient_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin','pharmacien'))
);
drop policy if exists assurance_sheets_insert on public.feuilles_assurance;
create policy assurance_sheets_insert on public.feuilles_assurance for insert to authenticated with check (
 medecin_id=auth.uid() and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('medecin','infirmier'))
);
drop policy if exists assurance_sheets_update on public.feuilles_assurance;
create policy assurance_sheets_update on public.feuilles_assurance for update to authenticated using (
 medecin_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
) with check (true);

drop policy if exists assurance_dispenses_select on public.delivrances_pharmacie;
create policy assurance_dispenses_select on public.delivrances_pharmacie for select to authenticated using (
 pharmacien_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
);
drop policy if exists assurance_dispenses_insert on public.delivrances_pharmacie;
create policy assurance_dispenses_insert on public.delivrances_pharmacie for insert to authenticated with check (pharmacien_id=auth.uid());

drop policy if exists assurance_journal_insert on public.journal_feuilles_assurance;
create policy assurance_journal_insert on public.journal_feuilles_assurance for insert to authenticated with check (acteur_id=auth.uid());
drop policy if exists assurance_journal_select on public.journal_feuilles_assurance;
create policy assurance_journal_select on public.journal_feuilles_assurance for select to authenticated using (
 acteur_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
);

